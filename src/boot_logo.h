// Helper to draw a mask layer with a given color
template <typename T>
static void drawLogoLayer(T& display, const uint8_t mask[BOOT_LOGO_ROWS][BOOT_LOGO_BYTES_PER_ROW], uint16_t color) {
    for (int r = 0; r < BOOT_LOGO_ROWS; ++r) {
        int y = BOOT_LOGO_OFFSET_Y + r * BOOT_LOGO_CELL_SIZE;
        for (int b = 0; b < BOOT_LOGO_BYTES_PER_ROW; ++b) {
            uint8_t byteVal = pgm_read_byte(&mask[r][b]);
            if (!byteVal) continue;
            for (int bit = 0; bit < 8; ++bit) {
                if (byteVal & (0x80 >> bit)) {
                    int c = b * 8 + bit;
                    if (c < BOOT_LOGO_COLS) {
                        int x = BOOT_LOGO_OFFSET_X + c * BOOT_LOGO_CELL_SIZE;
                        display.fillRect(x, y, BOOT_LOGO_DOT_SIZE, BOOT_LOGO_DOT_SIZE, color);
                    }
                }
            }
        }
    }
}

// Plays the 2.5-second ZoneNet boot animation with pulsing/radiating antenna waves
template <typename T>
inline void playZoneNetBootAnimation(T& display) {
    display.fillScreen(LOGO_COLOR_UNLIT);
    display.startWrite();

    // 1. Draw static Base Logo (Z body + ZONENET)
    drawLogoLayer(display, logo_base_bitmap, LOGO_COLOR_LIT);
    display.endWrite();

    unsigned long startTime = millis();
    int animPhase = 0;
    bool prevInner = false;
    bool prevOuter = false;

    // 2. Animate antennas for 2.5 seconds (2500 ms)
    while (millis() - startTime < 2500) {
        // Radiating pulse cycle:
        // Phase 0: Inner wave ON, Outer wave OFF (pulse begins)
        // Phase 1: Inner wave ON, Outer wave ON  (full signal burst)
        // Phase 2: Inner wave OFF, Outer wave ON (wave radiating outward)
        // Phase 3: Both OFF                     (pause between pulses)
        bool innerLit = (animPhase == 0 || animPhase == 1);
        bool outerLit = (animPhase == 1 || animPhase == 2);

        if (innerLit != prevInner || outerLit != prevOuter) {
            display.startWrite();
            if (innerLit != prevInner) {
                drawLogoLayer(display, logo_antenna_inner_bitmap, innerLit ? LOGO_COLOR_LIT : LOGO_COLOR_UNLIT);
                prevInner = innerLit;
            }
            if (outerLit != prevOuter) {
                drawLogoLayer(display, logo_antenna_outer_bitmap, outerLit ? LOGO_COLOR_LIT : LOGO_COLOR_UNLIT);
                prevOuter = outerLit;
            }
            display.endWrite();
        }

        animPhase = (animPhase + 1) % 4;
        delay(90); // ~360ms per pulse cycle -> ~7 full data pulses over 2.5 seconds
    }

    // Ensure antennas are fully lit at the end of boot
    display.startWrite();
    drawLogoLayer(display, logo_antenna_inner_bitmap, LOGO_COLOR_LIT);
    drawLogoLayer(display, logo_antenna_outer_bitmap, LOGO_COLOR_LIT);
    display.endWrite();
    delay(150);
}

